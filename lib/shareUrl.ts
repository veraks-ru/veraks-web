/**
 * Адрес события для ссылок, которыми делятся.
 *
 * Обычно совпадает с адресом сайта. Отличается, когда часть аудитории не может
 * достучаться до основного домена: хостинг платформы не имеет сетевой
 * связности с сетями Telegram, поэтому их парсер превью не забирает ни
 * страницу, ни картинку — ссылка в чате разворачивается пустой или висит.
 * ``NEXT_PUBLIC_SHARE_BASE`` указывает на зеркало, доступное таким парсерам;
 * оно отдаёт ту же страницу и ту же карточку.
 *
 * Переменной нет — берём адрес текущего сайта, то есть прежнее поведение.
 */
export function shareUrl(slug: string): string {
  const mirror = process.env.NEXT_PUBLIC_SHARE_BASE?.replace(/\/+$/, "");
  const origin =
    mirror || (typeof window === "undefined" ? "" : window.location.origin);
  return `${origin}/events/${slug}`;
}
