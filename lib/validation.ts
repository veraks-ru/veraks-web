// Клиентские проверки формата — только чтобы не гонять запрос за явной
// опечаткой. Итоговая валидация всегда на бэкенде.

// Тот же формат, что бэкенд валидирует в POST /users/me/onboarding и
// PATCH /users/me — используется и там, и там (app/onboarding, app/account).
export const USERNAME_RE = /^[a-z0-9][a-z0-9-]{1,30}[a-z0-9]$/;

// Простая проверка формата email — не строгая (RFC email куда сложнее),
// строгую валидацию делает бэкенд.
export const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
